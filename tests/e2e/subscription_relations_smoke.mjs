// Uses only an explicitly seeded disposable integration fixture.
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import {chromium} from 'playwright';
const base=process.env.WALLOS_UPSTREAM_TEST_URL || 'http://127.0.0.1:18284';
const fixture=JSON.parse(await fs.readFile(process.env.WALLOS_UPSTREAM_FIXTURE_FILE,'utf8'));
const key=JSON.parse(await fs.readFile(process.env.WALLOS_AGENT_TEST_KEY_FILE,'utf8')).token;
const browser=await chromium.launch({headless:true});
let checks=0;
const check=(ok,label)=>{assert(ok,label);console.log('[OK]',label);checks++;};
const requestId=()=>`relations-${crypto.randomUUID()}`;
try {
 const context=await browser.newContext({serviceWorkers:'block'});
 await context.addCookies([{name:'PHPSESSID',value:fixture.sessions['1'].id,url:base}]);
 const tool=async(name,args={})=>{
  const response=await context.request.post(base+'/api/agent/v1/index.php',{headers:{Authorization:'Bearer '+key},data:{tool:name,arguments:args}});
  assert.equal(response.status(),200,name);const result=await response.json();assert(result.success,JSON.stringify(result));return result.result;
 };
 assert.equal((await tool('wallos_context')).account.username,'agent-ui-test','Refuse writes outside disposable fixture');
 const page=await context.newPage(); const errors=[];page.on('pageerror',e=>errors.push(e.message));
 const suffix=crypto.randomUUID();
 const cats=[],payers=[];
 for(let i=0;i<2;i++) {
  cats.push((await tool('wallos_references_save',{kind:'categories',data:{name:`Relation Category ${i} ${suffix}`},request_id:requestId()})).reference);
  payers.push((await tool('wallos_references_save',{kind:'household',data:{name:`Relation Payer ${i} ${suffix}`},request_id:requestId()})).reference);
 }
 const name=`Multi relation browser ${suffix}`;
 await page.goto(base+'/subscriptions.php',{waitUntil:'networkidle'});
 await page.evaluate(()=>addSubscription());
 await page.locator('#name').fill(name);await page.locator('#price').fill('120');await page.locator('#next_payment').fill(new Date().toISOString().slice(0,10));
 await page.locator('#payer_user').selectOption(payers.map(r=>String(r.id)));
 await page.locator('#category').selectOption(cats.map(r=>String(r.id)));
 check(await page.locator('#payer_user').evaluate(el=>el.multiple && el.getBoundingClientRect().height>=100),'payer multi-select is visible and accessible');
 check(await page.locator('#category').evaluate(el=>el.multiple && el.getBoundingClientRect().height>=100),'category multi-select is visible and accessible');
 await page.locator('#currency').selectOption('100');await page.locator('#cycle').selectOption('3');await page.locator('#frequency').selectOption('1');
 await page.locator('#payment_method').selectOption('100');
 const submit=page.waitForResponse(r=>r.url().includes('/endpoints/subscription/add.php') && r.request().method()==='POST');
 await page.locator('#subs-form input[type=submit], #subs-form button[type=submit]').first().click();
 const saved=await (await submit).json();check(saved.status==='Success','web form creates a subscription with both relation lists');
 const item=(await tool('wallos_subscriptions_list',{limit:100})).subscriptions.find(s=>s.name===name);assert(item,'created subscription exists');
 check(item.payer_ids.length===2 && item.category_ids.length===2,'MCP reads full relation lists created through the browser');
 await page.goto(base+'/subscriptions.php',{waitUntil:'networkidle'});
 const card=page.locator(`.subscription[data-id="${item.id}"]`);
 const labels=await card.textContent();
 check(cats.every(r=>labels.includes(r.name)) && payers.every(r=>labels.includes(r.name)),'subscription card shows all assigned members and categories');
 await page.evaluate(id=>openEditSubscription({stopPropagation(){}},id),item.id);
 await page.waitForFunction(()=>Array.from(document.querySelector('#payer_user').selectedOptions).length===2);
 check((await page.locator('#category').evaluate(el=>Array.from(el.selectedOptions).length))===2,'edit modal restores all selected categories');
 await page.locator('#name').fill(name+' edited');
 const update=page.waitForResponse(r=>r.url().includes('/endpoints/subscription/add.php') && r.request().method()==='POST');
 await page.locator('#subs-form input[type=submit], #subs-form button[type=submit]').first().click();
 check((await (await update).json()).status==='Success','browser edit saves selected arrays');
 const data=await (await context.request.get(`${base}/endpoints/subscription/get.php?id=${item.id}`)).json();
 const detail=data.subscription || data;
 check((detail.payer_ids || []).length===2 && (detail.category_ids || []).length===2,'detail endpoint exposes arrays after web edit');
 await page.goto(base+`/subscriptions.php?category=${cats[1].id}`,{waitUntil:'networkidle'});
 check(await page.locator(`.subscription[data-id="${item.id}"]`).count()===1,'secondary category filter includes subscription once');
 await page.goto(base+`/subscriptions.php?member=${payers[1].id}`,{waitUntil:'networkidle'});
 check(await page.locator(`.subscription[data-id="${item.id}"]`).count()===1,'secondary payer filter includes subscription once');
 const statsResponse=await page.goto(base+`/stats.php?member=${payers[1].id}`,{waitUntil:'networkidle'});
 check(statsResponse.status()===200,'statistics render successfully with secondary payer filter');
 check((await page.locator('body').textContent()).includes(payers[1].name),'statistics accept filtering a secondary payer');
 const metrics=await page.locator('[data-metric-explanation]').evaluateAll(elements=>elements.map(el=>JSON.parse(el.dataset.metricExplanation)));
 const month=metrics.find(p=>p.items?.some(i=>i.name===name+' edited' && 'monthly_equivalent' in i));
 check(month?.total===60,'secondary payer receives exactly half of monthly cost');
 const actual=metrics.find(p=>p.items?.some(i=>i.subscription_name===name+' edited'));
 check(actual?.total===60,'actual payment display uses equal allocation without duplicate payment rows');
 await page.goto(base+`/stats.php?member=${payers[1].id}&category=${cats[1].id}`,{waitUntil:'networkidle'});
 const combined=await page.locator('[data-metric-explanation]').evaluateAll(elements=>elements.map(el=>JSON.parse(el.dataset.metricExplanation)));
 check(combined.find(p=>p.items?.some(i=>i.name===name+' edited' && 'monthly_equivalent' in i))?.total===30,'combined member/category filter applies independent equal shares');
 const headers={'X-CSRF-Token':fixture.sessions['1'].csrf};
 const cloned=await (await context.request.post(base+'/endpoints/subscription/clone.php',{headers,data:{id:item.id}})).json();
 check(cloned.success,'browser clone succeeds with assigned lists');
 const clone=(await tool('wallos_subscriptions_get',{id:cloned.id})).subscription;
 check(clone.payer_ids.length===2 && clone.category_ids.length===2,'clone retains complete associations');
 const trash=await (await context.request.post(base+'/endpoints/subscription/delete.php',{headers,data:{id:cloned.id}})).json();
 check(trash.success,'clone can move to recycle bin');
 const restore=await (await context.request.post(base+'/endpoints/subscription/restore.php',{headers,data:{id:cloned.id}})).json();
 check(restore.success,'clone can restore from recycle bin');
 const restored=(await tool('wallos_subscriptions_get',{id:cloned.id})).subscription;
 check(restored.payer_ids.length===2 && restored.category_ids.length===2,'recycle restore retains complete associations');
 const records=await tool('wallos_payments_list',{subscription_id:item.id});
 check(records.payments.length===1 && Number(records.payments[0].amount_original)===120,'actual payment ledger remains one original full-amount transaction');
 check(errors.length===0,'no browser exceptions in multi-relation lifecycle: '+errors.join('; '));
 console.log(`PASS: ${checks} multi-relation browser checks.`);
} finally { await browser.close(); }
